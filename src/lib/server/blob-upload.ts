import { createHmac, randomBytes, timingSafeEqual } from 'node:crypto';
import path from 'node:path';

/** Directory (storage prefix) that browser-direct uploads may write to. */
export const DIRECT_UPLOAD_PREFIX = 'downloads/';

/** Content types accepted for direct uploads (documents, archives, images). */
export const DIRECT_UPLOAD_CONTENT_TYPES = [
    'application/pdf',
    'application/msword',
    'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
    'application/vnd.ms-excel',
    'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
    'application/vnd.ms-powerpoint',
    'application/vnd.openxmlformats-officedocument.presentationml.presentation',
    'application/zip',
    'application/x-zip-compressed',
    'text/plain',
    'text/csv',
    'image/*',
];

const TICKET_TTL_MS = 10 * 60 * 1000;
const KEY_PATTERN = /^downloads\/[0-9a-f]{32}(\.[a-z0-9]{1,10})?$/;

/** True for keys of the form `downloads/<32 hex>[.ext]`, i.e. generated by `issueUploadKey`. */
export function isDirectUploadKey(key: string): boolean {
    return KEY_PATTERN.test(key);
}

function extensionOf(name: string): string {
    const ext = path
        .extname(name)
        .toLowerCase()
        .replace(/[^a-z0-9.]/g, '');
    return ext.length > 1 && ext.length <= 10 ? ext : '';
}

function sign(secret: string, userId: number, key: string, expires: number): string {
    return createHmac('sha256', secret).update(`${userId}\n${key}\n${expires}`).digest('base64url');
}

/**
 * Server-generated upload key plus a signed ticket bound to the user and key. The browser may only
 * upload to a key the server issued; `verifyUploadTicket` rejects anything else.
 */
export function issueUploadKey(
    secret: string,
    userId: number,
    fileName: string,
    now = Date.now(),
): { key: string; ticket: string } {
    const key = `${DIRECT_UPLOAD_PREFIX}${randomBytes(16).toString('hex')}${extensionOf(fileName)}`;
    const expires = now + TICKET_TTL_MS;
    return { key, ticket: `${expires}.${sign(secret, userId, key, expires)}` };
}

export function verifyUploadTicket(
    secret: string,
    userId: number,
    key: string,
    ticket: string | null | undefined,
    now = Date.now(),
): boolean {
    if (!ticket || !isDirectUploadKey(key)) return false;
    const [expiresText, signature] = ticket.split('.');
    const expires = Number(expiresText);
    if (!signature || !Number.isFinite(expires) || expires < now) return false;
    const expected = Buffer.from(sign(secret, userId, key, expires));
    const actual = Buffer.from(signature);
    return expected.length === actual.length && timingSafeEqual(expected, actual);
}
